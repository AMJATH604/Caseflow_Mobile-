/// Data models for the Case Strategy Board feature.
///
/// Provides [StrategyTask], [TaskComment], and [TaskActivity] models
/// for Kanban-style case task management.

import '../utils/safe_date.dart';
import 'enums.dart';

/// Priority levels for strategy tasks.
enum TaskPriority {
  low,
  medium,
  high,
  urgent;

  String get label => name[0].toUpperCase() + name.substring(1);

  String get emoji {
    switch (this) {
      case low:
        return '🟢';
      case medium:
        return '🟡';
      case high:
        return '🟠';
      case urgent:
        return '🔴';
    }
  }

  static TaskPriority fromString(String value) {
    return TaskPriority.values.firstWhere(
      (e) => e.name == value.toLowerCase(),
      orElse: () => TaskPriority.medium,
    );
  }
}

/// Kanban stages for the strategy board.
enum TaskStage {
  todo,
  inProgress,
  review,
  filed,
  done;

  String get label {
    switch (this) {
      case todo:
        return 'To Do';
      case inProgress:
        return 'In Progress';
      case review:
        return 'Review';
      case filed:
        return 'Filed';
      case done:
        return 'Done';
    }
  }

  String get emoji {
    switch (this) {
      case todo:
        return '📋';
      case inProgress:
        return '🔍';
      case review:
        return '✍️';
      case filed:
        return '📤';
      case done:
        return '✅';
    }
  }

  /// Database column value.
  String get dbValue {
    switch (this) {
      case todo:
        return 'todo';
      case inProgress:
        return 'in_progress';
      case review:
        return 'review';
      case filed:
        return 'filed';
      case done:
        return 'done';
    }
  }

  static TaskStage fromString(String value) {
    final clean = value.toLowerCase().replaceAll('_', '');
    return TaskStage.values.firstWhere(
      (e) =>
          e.name.toLowerCase() == clean ||
          e.dbValue.replaceAll('_', '') == clean,
      orElse: () => TaskStage.todo,
    );
  }
}

/// A single task card on the strategy board.
class StrategyTask {
  final String id;
  final String caseId;
  final String title;
  final String? description;
  final TaskStage stage;
  final int position;
  final String? assignedTo;
  final String? assignedToName;
  final String? assignedToAvatarUrl;
  final String createdBy;
  final String? createdByName;
  final TaskPriority priority;
  final DateTime? dueDate;
  final String? linkedHearingId;
  final String? firmId;
  final bool isAutoGenerated;
  final DateTime? completedAt;
  final DateTime createdAt;
  final DateTime updatedAt;
  final int commentCount;
  final int attachmentCount;

  StrategyTask({
    required this.id,
    required this.caseId,
    required this.title,
    this.description,
    this.stage = TaskStage.todo,
    this.position = 0,
    this.assignedTo,
    this.assignedToName,
    this.assignedToAvatarUrl,
    required this.createdBy,
    this.createdByName,
    this.priority = TaskPriority.medium,
    this.dueDate,
    this.linkedHearingId,
    this.firmId,
    this.isAutoGenerated = false,
    this.completedAt,
    required this.createdAt,
    required this.updatedAt,
    this.commentCount = 0,
    this.attachmentCount = 0,
  });

  factory StrategyTask.fromJson(Map<String, dynamic> json) {
    // Handle comment/attachment counts from Supabase aggregate joins
    int commentCt = 0;
    if (json['task_comments'] is List) {
      final list = json['task_comments'] as List;
      if (list.isNotEmpty && list[0] is Map && list[0]['count'] != null) {
        commentCt = list[0]['count'] as int;
      } else {
        commentCt = list.length;
      }
    }
    int attachCt = 0;
    if (json['task_attachments'] is List) {
      final list = json['task_attachments'] as List;
      if (list.isNotEmpty && list[0] is Map && list[0]['count'] != null) {
        attachCt = list[0]['count'] as int;
      } else {
        attachCt = list.length;
      }
    }

    return StrategyTask(
      id: json['id'] ?? '',
      caseId: json['case_id'] ?? '',
      title: json['title'] ?? '',
      description: json['description'],
      stage: TaskStage.fromString(json['stage'] ?? 'todo'),
      position: json['position'] ?? 0,
      assignedTo: json['assigned_to'],
      assignedToName: json['assigned_profile']?['full_name'],
      assignedToAvatarUrl: json['assigned_profile']?['avatar_url'],
      createdBy: json['created_by'] ?? '',
      createdByName: json['creator_profile']?['full_name'],
      priority: TaskPriority.fromString(json['priority'] ?? 'medium'),
      dueDate:
          parseDateOrNull(json['due_date']),
      linkedHearingId: json['linked_hearing_id'],
      firmId: json['firm_id'],
      isAutoGenerated: json['is_auto_generated'] ?? false,
      completedAt: parseDateOrNull(json['completed_at']),
      createdAt: parseDateOr(json['created_at'], DateTime.now()),
      updatedAt: parseDateOr(json['updated_at'], DateTime.now()),
      commentCount: commentCt,
      attachmentCount: attachCt,
    );
  }

  Map<String, dynamic> toInsertJson() => {
        'case_id': caseId,
        'title': title,
        'description': description,
        'stage': stage.dbValue,
        'position': position,
        'assigned_to': assignedTo,
        'created_by': createdBy,
        'priority': priority.name,
        'due_date': dueDate?.toIso8601String().split('T').first,
        'linked_hearing_id': linkedHearingId,
        'firm_id': firmId,
        'is_auto_generated': isAutoGenerated,
      };

  /// Whether the task is past its due date and not completed.
  bool get isOverdue =>
      dueDate != null &&
      stage != TaskStage.done &&
      dueDate!.isBefore(DateTime.now());

  /// Days until due (negative = overdue).
  int? get daysUntilDue =>
      dueDate != null ? dueDate!.difference(DateTime.now()).inDays : null;

  /// Create a copy with updated fields.
  StrategyTask copyWith({
    String? title,
    String? description,
    TaskStage? stage,
    int? position,
    String? assignedTo,
    String? assignedToName,
    TaskPriority? priority,
    DateTime? dueDate,
    String? linkedHearingId,
  }) {
    return StrategyTask(
      id: id,
      caseId: caseId,
      title: title ?? this.title,
      description: description ?? this.description,
      stage: stage ?? this.stage,
      position: position ?? this.position,
      assignedTo: assignedTo ?? this.assignedTo,
      assignedToName: assignedToName ?? this.assignedToName,
      assignedToAvatarUrl: assignedToAvatarUrl,
      createdBy: createdBy,
      createdByName: createdByName,
      priority: priority ?? this.priority,
      dueDate: dueDate ?? this.dueDate,
      linkedHearingId: linkedHearingId ?? this.linkedHearingId,
      firmId: firmId,
      isAutoGenerated: isAutoGenerated,
      completedAt: completedAt,
      createdAt: createdAt,
      updatedAt: updatedAt,
      commentCount: commentCount,
      attachmentCount: attachmentCount,
    );
  }
}

/// A comment on a strategy task.
class TaskComment {
  final String id;
  final String taskId;
  final String userId;
  final String? userName;
  final String? userAvatarUrl;
  final String content;
  final DateTime createdAt;

  TaskComment({
    required this.id,
    required this.taskId,
    required this.userId,
    this.userName,
    this.userAvatarUrl,
    required this.content,
    required this.createdAt,
  });

  factory TaskComment.fromJson(Map<String, dynamic> json) => TaskComment(
        id: json['id'] ?? '',
        taskId: json['task_id'] ?? '',
        userId: json['user_id'] ?? '',
        userName: json['profiles']?['full_name'],
        userAvatarUrl: json['profiles']?['avatar_url'],
        content: json['content'] ?? '',
        createdAt: parseDateOr(json['created_at'], DateTime.now()),
      );
}

/// Activity log entry for full audit trail.
class TaskActivity {
  final String id;
  final String taskId;
  final String userId;
  final String? userName;
  final String action;
  final String? oldValue;
  final String? newValue;
  final DateTime createdAt;

  TaskActivity({
    required this.id,
    required this.taskId,
    required this.userId,
    this.userName,
    required this.action,
    this.oldValue,
    this.newValue,
    required this.createdAt,
  });

  factory TaskActivity.fromJson(Map<String, dynamic> json) => TaskActivity(
        id: json['id'] ?? '',
        taskId: json['task_id'] ?? '',
        userId: json['user_id'] ?? '',
        userName: json['profiles']?['full_name'],
        action: json['action'] ?? '',
        oldValue: json['old_value'],
        newValue: json['new_value'],
        createdAt: parseDateOr(json['created_at'], DateTime.now()),
      );

  /// Human-readable description of what happened.
  String get description {
    final name = userName ?? 'Someone';
    switch (action) {
      case 'created':
        return '$name created this task';
      case 'moved':
        return '$name moved from $oldValue → $newValue';
      case 'assigned':
        return '$name assigned to $newValue';
      case 'commented':
        return '$name added a comment';
      case 'completed':
        return '$name marked as done ✅';
      case 'updated':
        return '$name updated $newValue';
      default:
        return '$name performed $action';
    }
  }
}

/// Attachment linked to a strategy task.
class TaskAttachment {
  final String id;
  final String taskId;
  final String uploadedBy;
  final String fileUrl;
  final String fileName;
  final int? fileSize;
  final String? mimeType;
  final DateTime createdAt;

  TaskAttachment({
    required this.id,
    required this.taskId,
    required this.uploadedBy,
    required this.fileUrl,
    required this.fileName,
    this.fileSize,
    this.mimeType,
    required this.createdAt,
  });

  factory TaskAttachment.fromJson(Map<String, dynamic> json) => TaskAttachment(
        id: json['id'] ?? '',
        taskId: json['task_id'] ?? '',
        uploadedBy: json['uploaded_by'] ?? '',
        fileUrl: json['file_url'] ?? '',
        fileName: json['file_name'] ?? '',
        fileSize: json['file_size'],
        mimeType: json['mime_type'],
        createdAt: parseDateOr(json['created_at'], DateTime.now()),
      );

  /// Human-readable file size.
  String get fileSizeLabel {
    if (fileSize == null) return '';
    if (fileSize! < 1024) return '${fileSize}B';
    if (fileSize! < 1024 * 1024) return '${(fileSize! / 1024).toStringAsFixed(0)}KB';
    return '${(fileSize! / (1024 * 1024)).toStringAsFixed(1)}MB';
  }
}
